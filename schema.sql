-- BCFACHAT database setup for Supabase
-- Run this entire script in Supabase Dashboard > SQL Editor.
-- All exposed application tables have RLS enabled. Never put service_role keys in the browser.

create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique check (username ~ '^[a-zA-Z0-9_.-]{3,20}$'),
  name_english text not null default 'New member' check (name_english ~ '^[A-Za-z][A-Za-z .''-]{0,49}$'),
  age smallint not null default 18 check (age between 18 and 99),
  weight numeric(5,1) null check (weight is null or weight between 25 and 300),
  height numeric(5,1) null check (height is null or height between 80 and 250),
  status text not null default 'Single' check (status in ('Single', 'Open to talk', 'Complicated', 'In a relationship')),
  play_line text not null default 'NoL' check (play_line in ('BL', 'HL', 'GL', 'NoL', 'FZ')),
  interests jsonb not null default '{"animals":"","music":"","sports":"","movies":"","hobbies":""}'::jsonb,
  bio text not null default '' check (char_length(bio) <= 300),
  photo_urls text[] not null default '{}',
  theme text not null default 'sky' check (theme in ('sky', 'lilac', 'peach', 'mint', 'cream', 'midnight', 'blue')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Birthday is private: keep it separate from profile discovery data.
-- This also migrates projects that ran an earlier version of this schema.
alter table public.profiles drop column if exists birthday;

create table if not exists public.profile_private_details (
  id uuid primary key references public.profiles(id) on delete cascade,
  birthday date null,
  updated_at timestamptz not null default now()
);

create table if not exists public.swipes (
  id bigint generated by default as identity primary key,
  from_user uuid not null references public.profiles(id) on delete cascade,
  to_user uuid not null references public.profiles(id) on delete cascade,
  liked boolean not null,
  created_at timestamptz not null default now(),
  constraint swipes_no_self check (from_user <> to_user),
  constraint swipes_one_direction unique (from_user, to_user)
);

create table if not exists public.matches (
  id uuid primary key default gen_random_uuid(),
  user_a uuid not null references public.profiles(id) on delete cascade,
  user_b uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  constraint matches_two_people check (user_a < user_b),
  constraint matches_unique_pair unique (user_a, user_b)
);

create table if not exists public.messages (
  id uuid primary key default gen_random_uuid(),
  match_id uuid not null references public.matches(id) on delete cascade,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  recipient_id uuid not null references public.profiles(id) on delete cascade,
  body text null check (body is null or char_length(body) <= 2000),
  image_path text null,
  created_at timestamptz not null default now(),
  constraint messages_body_or_image check (
    (body is not null and char_length(trim(body)) > 0) or image_path is not null
  ),
  constraint messages_no_self check (sender_id <> recipient_id)
);

create index if not exists profiles_discovery_idx on public.profiles (created_at desc, age, play_line);
create index if not exists swipes_from_user_idx on public.swipes (from_user, created_at desc);
create index if not exists swipes_reciprocal_idx on public.swipes (to_user, from_user, liked);
create index if not exists matches_user_a_idx on public.matches (user_a, created_at desc);
create index if not exists matches_user_b_idx on public.matches (user_b, created_at desc);
create index if not exists messages_match_created_idx on public.messages (match_id, created_at asc);

alter table public.profiles enable row level security;
alter table public.profile_private_details enable row level security;
alter table public.swipes enable row level security;
alter table public.matches enable row level security;
alter table public.messages enable row level security;

-- Profiles are visible to signed-in members so they can discover each other.
drop policy if exists "Signed-in members can view profiles" on public.profiles;
create policy "Signed-in members can view profiles" on public.profiles
  for select to authenticated using (true);
drop policy if exists "Members can create their own profile" on public.profiles;
create policy "Members can create their own profile" on public.profiles
  for insert to authenticated with check ((select auth.uid()) = id);
drop policy if exists "Members can update their own profile" on public.profiles;
create policy "Members can update their own profile" on public.profiles
  for update to authenticated using ((select auth.uid()) = id) with check ((select auth.uid()) = id);

-- Birthdays may only be read and changed by their owner.
drop policy if exists "Members can read their own private profile details" on public.profile_private_details;
create policy "Members can read their own private profile details" on public.profile_private_details
  for select to authenticated using ((select auth.uid()) = id);
drop policy if exists "Members can create their own private profile details" on public.profile_private_details;
create policy "Members can create their own private profile details" on public.profile_private_details
  for insert to authenticated with check ((select auth.uid()) = id);
drop policy if exists "Members can update their own private profile details" on public.profile_private_details;
create policy "Members can update their own private profile details" on public.profile_private_details
  for update to authenticated using ((select auth.uid()) = id) with check ((select auth.uid()) = id);

-- Members may inspect only their own outgoing swipes. Writes are performed via record_swipe().
drop policy if exists "Members can view their own swipes" on public.swipes;
create policy "Members can view their own swipes" on public.swipes
  for select to authenticated using ((select auth.uid()) = from_user);
revoke all on public.profile_private_details from anon;
grant select, insert, update on public.profile_private_details to authenticated;
revoke insert, update, delete on public.swipes from anon, authenticated;
grant select on public.swipes to authenticated;

-- A match is visible only to either participant.
drop policy if exists "Match participants can read matches" on public.matches;
create policy "Match participants can read matches" on public.matches
  for select to authenticated using ((select auth.uid()) = user_a or (select auth.uid()) = user_b);
revoke insert, update, delete on public.matches from anon, authenticated;
grant select on public.matches to authenticated;

-- Messages are readable only by the two people in that match.
drop policy if exists "Match participants can read messages" on public.messages;
create policy "Match participants can read messages" on public.messages
  for select to authenticated using (
    exists (
      select 1 from public.matches m
      where m.id = messages.match_id
        and ((select auth.uid()) = m.user_a or (select auth.uid()) = m.user_b)
        and ((select auth.uid()) = messages.sender_id or (select auth.uid()) = messages.recipient_id)
    )
  );
drop policy if exists "Match participants can send messages" on public.messages;
create policy "Match participants can send messages" on public.messages
  for insert to authenticated with check (
    (select auth.uid()) = sender_id
    and exists (
      select 1 from public.matches m
      where m.id = messages.match_id
        and (
          (m.user_a = (select auth.uid()) and m.user_b = messages.recipient_id)
          or (m.user_b = (select auth.uid()) and m.user_a = messages.recipient_id)
        )
    )
  );
revoke update, delete on public.messages from anon, authenticated;
grant select, insert on public.messages to authenticated;

-- Record a swipe and create one match only when both people have liked one another.
create or replace function public.record_swipe(p_target_user uuid, p_liked boolean)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_me uuid := auth.uid();
  v_match_id uuid;
  v_matched boolean := false;
  v_user_a uuid;
  v_user_b uuid;
begin
  if v_me is null then
    raise exception 'Authentication required';
  end if;
  if p_target_user is null or p_target_user = v_me then
    raise exception 'Invalid target user';
  end if;
  if not exists (select 1 from public.profiles p where p.id = p_target_user) then
    raise exception 'Target profile not found';
  end if;

  insert into public.swipes (from_user, to_user, liked)
  values (v_me, p_target_user, coalesce(p_liked, false))
  on conflict (from_user, to_user)
  do update set liked = excluded.liked, created_at = now();

  if coalesce(p_liked, false) and exists (
    select 1 from public.swipes s
    where s.from_user = p_target_user and s.to_user = v_me and s.liked = true
  ) then
    v_user_a := least(v_me, p_target_user);
    v_user_b := greatest(v_me, p_target_user);
    insert into public.matches (user_a, user_b)
    values (v_user_a, v_user_b)
    on conflict (user_a, user_b) do nothing;
    select m.id into v_match_id from public.matches m
    where m.user_a = v_user_a and m.user_b = v_user_b;
    v_matched := v_match_id is not null;
  end if;

  return jsonb_build_object('matched', v_matched, 'match_id', v_match_id);
end;
$$;
revoke all on function public.record_swipe(uuid, boolean) from public, anon;
grant execute on function public.record_swipe(uuid, boolean) to authenticated;

-- Storage buckets. Profile images are public to signed-in members; chat images are private and signed by the app.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('profile-media', 'profile-media', true, 8388608, array['image/jpeg','image/png','image/webp','image/gif'])
on conflict (id) do update set public = true, file_size_limit = 8388608, allowed_mime_types = array['image/jpeg','image/png','image/webp','image/gif'];
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('chat-media', 'chat-media', false, 5242880, array['image/jpeg','image/png','image/webp','image/gif'])
on conflict (id) do update set public = false, file_size_limit = 5242880, allowed_mime_types = array['image/jpeg','image/png','image/webp','image/gif'];

drop policy if exists "Members can read profile media" on storage.objects;
create policy "Members can read profile media" on storage.objects
  for select to authenticated using (bucket_id = 'profile-media');
drop policy if exists "Members can upload their own profile media" on storage.objects;
create policy "Members can upload their own profile media" on storage.objects
  for insert to authenticated with check (
    bucket_id = 'profile-media' and (storage.foldername(name))[1] = (select auth.uid())::text
  );
drop policy if exists "Members can delete their own profile media" on storage.objects;
create policy "Members can delete their own profile media" on storage.objects
  for delete to authenticated using (
    bucket_id = 'profile-media' and (storage.foldername(name))[1] = (select auth.uid())::text
  );

drop policy if exists "Match participants can read chat media" on storage.objects;
create policy "Match participants can read chat media" on storage.objects
  for select to authenticated using (
    bucket_id = 'chat-media'
    and exists (
      select 1 from public.matches m
      where m.id::text = (storage.foldername(name))[1]
        and ((select auth.uid()) = m.user_a or (select auth.uid()) = m.user_b)
    )
  );
drop policy if exists "Members can upload chat media for their match" on storage.objects;
create policy "Members can upload chat media for their match" on storage.objects
  for insert to authenticated with check (
    bucket_id = 'chat-media'
    and (storage.foldername(name))[2] = (select auth.uid())::text
    and exists (
      select 1 from public.matches m
      where m.id::text = (storage.foldername(name))[1]
        and ((select auth.uid()) = m.user_a or (select auth.uid()) = m.user_b)
    )
  );
drop policy if exists "Members can delete their chat media" on storage.objects;
create policy "Members can delete their chat media" on storage.objects
  for delete to authenticated using (
    bucket_id = 'chat-media'
    and (storage.foldername(name))[2] = (select auth.uid())::text
    and exists (
      select 1 from public.matches m
      where m.id::text = (storage.foldername(name))[1]
        and ((select auth.uid()) = m.user_a or (select auth.uid()) = m.user_b)
    )
  );

-- Enable Supabase Realtime for durable chat history plus live updates.
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'messages'
  ) then
    alter publication supabase_realtime add table public.messages;
  end if;
end $$;
